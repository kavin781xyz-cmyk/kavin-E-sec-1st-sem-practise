#include<stdio.h>
int main()
{
  int a,b;
  printf("ENTER THE FIRST NUMBER=");
  scanf("%d",&a);
  printf("ENTER THE SECOND NUMBER=");
  scanf("%d",&b);
  printf("GREATER THAN(>)=%d\n",a>b);
  printf("LESSER THAN(<)=%d\n",a<b);
  printf("EQUAL TO(==)=%d\n",a==b);
  printf("(<=)=%d\n",a<=b);
  printf("(>=)=%d\n",a>=b);
  return 0;
}
